#!/usr/bin/env node

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const GENERATED_AT = "2026-06-29T07:45:00Z";
const MIGRATION =
  "drizzle/migrations/0032_seed_remaining_detail_page_content.sql";
const PROJECTS_DIR = "apps/www/src/content/projects";
const WRITING_DIR = "apps/www/src/content/writing";
const EXISTING_PAGE_KEYS = new Set([
  "project:quantercise",
  "writing:saturdays-are-for-claude-code",
]);

const projectRecords = markdownFiles(PROJECTS_DIR)
  .map((file) => projectRecord(file))
  .filter((record) => !EXISTING_PAGE_KEYS.has(record.pageKey));

const writingRecords = markdownFiles(WRITING_DIR)
  .map((file) => writingRecord(file))
  .filter((record) => !EXISTING_PAGE_KEYS.has(record.pageKey));

const records = [...projectRecords, ...writingRecords];

const sql = [
  "-- 0032_seed_remaining_detail_page_content.sql",
  "-- Generated by scripts/admin/generate-detail-page-content-seed.mjs.",
  "-- Seed the remaining tracked project and writing detail records into page_content.",
  "--",
  "-- This keeps source markdown as rollback/fallback while proving the D1 detail",
  "-- content path for every current public detail route and hidden/draft review row.",
  "-- It does not add save APIs, publish writes, newsletter sends, source rewrites,",
  "-- Cloudflare Access changes, or external mutations.",
  "--",
  "-- Rollback:",
  "--   DELETE FROM page_content",
  "--   WHERE id IN (",
  ...records.map(
    (record, index) =>
      `--     '${record.pageId}'${index === records.length - 1 ? "" : ","}`,
  ),
  "--   );",
  "--   DELETE FROM content_draft_operations",
  "--   WHERE operation_id IN (",
  ...records.map(
    (record, index) =>
      `--     '${record.operation.operation_id}'${
        index === records.length - 1 ? "" : ","
      }`,
  ),
  "--   );",
  "",
  ...records.flatMap((record) => [
    insertPageContent(record),
    "",
    insertContentOperation(record.operation),
    "",
  ]),
].join("\n");

writeFileSync(MIGRATION, `${sql.trimEnd()}\n`);
console.log(
  `wrote ${MIGRATION} with ${records.length} page_content rows and ${records.length} inert operations`,
);

function markdownFiles(dir) {
  return readdirSync(dir)
    .filter((file) => file.endsWith(".md"))
    .sort()
    .map((file) => join(dir, file));
}

function projectRecord(file) {
  const { frontmatter, body } = parseMarkdown(file);
  const slug = slugFromFile(file, frontmatter.slug);
  const visible = frontmatter.visible !== false;
  const content = {
    slug,
    title: asString(frontmatter.title, slug),
    status: asString(frontmatter.status, "wip"),
    year: asString(frontmatter.year, ""),
    range: asString(frontmatter.duration, ""),
    tags: asStringArray(frontmatter.tags).map((tag) => tag.toLowerCase()),
    summary: asString(frontmatter.subtitle, frontmatter.description ?? ""),
    body: body.trim() || asString(frontmatter.description, ""),
    links: [
      frontmatter.link_live
        ? { label: "live site", url: asString(frontmatter.link_live, "") }
        : null,
      frontmatter.link_repo
        ? { label: "source", url: asString(frontmatter.link_repo, "") }
        : null,
    ].filter(Boolean),
    featured: frontmatter.featured === true,
    order: asNumber(frontmatter.sort_order, 0),
    visible,
  };
  const pageKey = `project:${slug}`;
  return {
    surface: "project",
    sourceFile: file,
    pageKey,
    pageId: `page-project-${slug}-v1-2026-06-29`,
    published: visible,
    route: `/projects/${slug}`,
    content,
    operation: operationFor({
      surface: "projects",
      slug,
      route: `/projects/${slug}`,
      pageKey,
      sourceFile: file,
      published: visible,
      proposedValue: `Review future edits to the ${content.title} title, summary, body, links, tags, and visibility through preview-only operations before any save path edits page_content.`,
      forbiddenActions: [
        "save",
        "publish",
        "deploy",
        "rewrite_markdown",
        "sync_external",
      ],
    }),
  };
}

function writingRecord(file) {
  const { frontmatter, body } = parseMarkdown(file);
  const slug = slugFromFile(file, frontmatter.slug);
  const visible = asString(frontmatter.status, "draft") === "published";
  const content = {
    slug,
    title: asString(frontmatter.title, slug),
    date: asString(frontmatter.published_at, ""),
    tags: asStringArray(frontmatter.tags).map((tag) => tag.toLowerCase()),
    preview: asString(frontmatter.summary, ""),
    body: body.trim(),
    sourceLinks: frontmatter.artifact_url
      ? [
          {
            label: asString(frontmatter.artifact_type, "source"),
            url: asString(frontmatter.artifact_url, ""),
          },
        ]
      : [],
    visible,
    order: Number(asString(frontmatter.published_at, "").replaceAll("-", "")),
  };
  const pageKey = `writing:${slug}`;
  return {
    surface: "writing",
    sourceFile: file,
    pageKey,
    pageId: `page-writing-${slug}-v1-2026-06-29`,
    published: visible,
    route: `/writing/${slug}`,
    content,
    operation: operationFor({
      surface: "writing",
      slug,
      route: `/writing/${slug}`,
      pageKey,
      sourceFile: file,
      published: visible,
      proposedValue: `Review future edits to the ${content.title} title, summary, body, source links, tags, and publish visibility through preview-only operations before any save path edits page_content.`,
      forbiddenActions: [
        "save",
        "publish",
        "send",
        "schedule",
        "rewrite_markdown",
        "sync_provider",
      ],
    }),
  };
}

function operationFor({
  surface,
  slug,
  route,
  pageKey,
  sourceFile,
  published,
  proposedValue,
  forbiddenActions,
}) {
  const singularSurface = surface === "projects" ? "project" : "writing";
  const operationId = `content-draft-${singularSurface}-${slug}-detail-2026-06-29`;
  const unavailableActions = forbiddenActions.includes("send")
    ? "send, schedule, save route, or publish event"
    : "save route, source rewrite, external sync, or publish event";
  return {
    operation_id: operationId,
    kind: "content_draft",
    surface: "public_site",
    route,
    source_ref: `D1 page_content:${pageKey} seeded by ${MIGRATION}, fallback ${sourceFile}`,
    field_path: `${surface}.${slug.replaceAll("-", "_")}.detail`,
    current_value_ref: `${published ? "published" : "unpublished"}_page_content:${pageKey}`,
    proposed_value: proposedValue,
    status: "previewed",
    risk_level: published ? "medium" : "low",
    authority_state: "detail_page_content_preview_only_no_write",
    required_approval_ids: [],
    allowed_actions: ["render_preview", "request_review"],
    forbidden_actions: forbiddenActions,
    preview_targets: published
      ? ["/content/review", "/content/preview", route]
      : ["/content/review", "/content/preview"],
    proof_ids: [
      `content.${surface}.${slug.replaceAll("-", ".")}.page-content`,
      "admin.content.preview.d1",
    ],
    evidence_uri: `repo://${sourceFile}`,
    redaction: "public_copy_only",
    created_by: "agent",
    created_at: GENERATED_AT,
    updated_at: GENERATED_AT,
    expires_at: "2026-07-29T07:45:00Z",
    rollback_ref: `source_markdown:${sourceFile}`,
    reviewer_note: `${published ? "Published" : "Unpublished"} detail row seeded as inert preview metadata. No ${unavailableActions} is created.`,
    metadata: { source_migration: MIGRATION },
  };
}

